// Seams for tests.
var (
	sbxLookPath = exec.LookPath
	// sbxHandOver ends jira by handing the terminal to `sbx args...` in dir.
	sbxHandOver = execSbx
	// sbxRun runs sbx in dir; attach connects the terminal (sbx prompts),
	// otherwise the combined output is returned.
	sbxRun = func(ctx context.Context, dir string, attach bool, args ...string) ([]byte, error) {
		cmd := exec.CommandContext(ctx, "sbx", args...)
		cmd.Dir = dir
		if attach {
			cmd.Stdin, cmd.Stdout, cmd.Stderr = os.Stdin, os.Stdout, os.Stderr
			return nil, cmd.Run()
		}
		return cmd.CombinedOutput()
	}
)

type sbxFlags struct {
	o                     sbx.Options
	allowWrites, noSkill  bool
	binaryFile, sourceDir string
	skipChecks, run       bool
	interactive           bool
}

func (a *App) setupSbxCmd() *cobra.Command {
	f := &sbxFlags{}
	c := &cobra.Command{
		Use:   "setup-sbx",
		Short: "Set up a Docker Sandbox (sbx) in which an AI agent can use jira-cli",
		Long: `Sets up a Docker Sandboxes (sbx) environment in which an AI agent can use
jira-cli. The Jira personal access token stays on this machine as an sbx
secret; inside the sandbox JIRA_CREDENTIAL_<REF> is only a sentinel that the
sbx proxy replaces with the real Authorization header for your Jira host.

It stops at the first problem, and writes nothing before everything passed:
  1. checks: sbx installed, a linux jira binary, the existing sbx secrets;
  2. answers (asked without flags in a terminal), each checked when given,
     the Jira host included; a known setup is one confirmation;
  3. sbx checks the complete environment ('sbx env plan' on a scratch copy)
     and, when it knows the agent kit under another name, that name is used;
  4. the PAT: the sbx secret exists, or sbx stores it now (it prompts);
  5. files are written, and the next steps printed.

Files: <project>/.sbx/jira-cli (kit), <project>/sbxenv.yaml,
<project>/.opencode/skills/jira, and <settings>/config.yaml and bashrc
(created once, yours to edit). See docs/sandbox.md.`,
		Example: `  jira setup-sbx
  jira setup-sbx --project ~/Projects/my-work --base-url https://jira.company.internal \
    --agent registry.example.com/team/opencode:2.1 --image registry.example.com/team/sandbox:1`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			s := &sbxSetup{a: a, f: f, set: cmd.Flags().Changed, ui: a.newSbxUI(),
				guided: f.interactive || (cmd.Flags().NFlag() == 0 && a.IsTerminal())}
			return s.run(cmd.Context())
		},
	}
	cfgHome := os.Getenv("XDG_CONFIG_HOME")
	if cfgHome == "" {
		home, _ := os.UserHomeDir()
		cfgHome = filepath.Join(home, ".config")
	}
	fl := c.Flags()
	fl.StringVar(&f.o.Project, "project", "", "folder the agent works in; sbxenv.yaml goes here (default: current directory)")
	fl.StringVar(&f.o.BaseURL, "base-url", "", "Jira base URL (default: from <settings>/config.yaml)")
	fl.StringVar(&f.o.Agent, "agent", "opencode", "a built-in sbx agent, or an agent kit reference (registry/repo:tag)")
	fl.StringVar(&f.o.Image, "image", "", "sandbox image instead of the agent's default")
	fl.StringVar(&f.o.Name, "name", "", "sandbox name (default for a new project: <agent>-<folder>-jira)")
	fl.StringVar(&f.o.Secret, "secret", "jira", "sbx secret that holds the PAT")
	fl.BoolVar(&f.allowWrites, "allow-writes", false, "let the agent write to Jira (default: read-only)")
	fl.BoolVar(&f.noSkill, "no-skill", false, "do not install the skill in <project>/.opencode/skills/jira")
	fl.StringVar(&f.o.Settings, "settings", filepath.Join(cfgHome, "jira-cli-sbx"), "folder for config.yaml and bashrc")
	fl.StringVar(&f.binaryFile, "binary-file", "", "linux jira binary for the kit (default: this jira, a build from a clone, or the release)")
	fl.StringVar(&f.sourceDir, "source-dir", "", "jira-cli clone to build the linux binary from (default: the clone containing the current directory)")
	fl.BoolVar(&f.o.Force, "force", false, "replace an sbxenv.yaml not generated by jira-cli, and an edited skill")
	fl.BoolVar(&f.skipChecks, "skip-checks", false, "only write the files: no sbx, reachability or secret checks")
	fl.BoolVar(&f.run, "run", false, "start the sandbox at the end (sbx env run)")
	fl.BoolVarP(&f.interactive, "interactive", "i", false, "ask for every setting (default without flags in a terminal)")
	return c
}

// sbxSetup is one run of setup-sbx.
type sbxSetup struct {
	a      *App
	f      *sbxFlags
	set    func(flag string) bool
	ui     *sbxUI
	guided bool

	haveSbx       bool            // sbx usable here (not in the wrapper's container)
	secrets       map[string]bool // existing sbx secrets
	bin, binSrc   string          // the linux jira binary for the kit
	tmp           string
	nameDefaulted bool // the sandbox name follows the agent: <agent>-<folder>-jira
}

func (s *sbxSetup) o() *sbx.Options { return &s.f.o }

func (s *sbxSetup) fail(layer clierr.Layer, code string, err error, hint string) error {
	e := clierr.Wrap(layer, code, err.Error(), nil)
	if hint != "" {
		e = e.WithHint(hint)
	}
	return e
}

func (s *sbxSetup) run(ctx context.Context) error {
	if ctx == nil {
		ctx = context.Background()
	}
	o := s.o()
	o.ReadOnly, o.Skill = !s.f.allowWrites, !s.f.noSkill
	if o.Project == "" {
		o.Project, _ = os.Getwd()
	}
	o.Project, o.Settings = absPath(o.Project), absPath(o.Settings)
	format, err := s.a.Format()
	if err != nil {
		return err
	}
	s.ui.title("Docker Sandbox for jira-cli")
	if !s.guided { // flags are complete: validate them before any work
		s.applyDefaults()
		if _, err := sbx.NewPlan(*o); err != nil {
			return s.fail(clierr.LayerUsage, "invalid_setup", err, "")
		}
	}
	defer func() {
		if s.tmp != "" {
			os.RemoveAll(s.tmp)
		}
	}()

	if err := s.checks(ctx); err != nil {
		return err
	}
	if s.guided {
		if err := s.ask(ctx); err != nil {
			return err
		}
	} else if !s.f.skipChecks {
		if err := sbx.CheckReachable(ctx, s.baseURL()); err != nil {
			return s.fail(clierr.LayerTCP, "jira_unreachable", err, "")
		}
	}
	plan, err := sbx.NewPlan(*o)
	if err == nil {
		err = plan.CheckEnvFile()
	}
	if err != nil {
		return s.fail(clierr.LayerUsage, "invalid_setup", err, "")
	}
	if s.a.dryRun {
		env, _ := plan.EnvFileContent()
		return output.Write(s.a.Out, map[string]any{"dry_run": true, "project": plan.Project, "agent": plan.AgentName,
			"name": plan.Name, "jira_host": plan.Host, "secret": plan.Secret, "sbxenv_yaml": env}, format)
	}
	if s.haveSbx {
		if err := s.validate(ctx, plan); err != nil {
			return err
		}
		if err := s.ensureSecret(ctx, plan.Secret); err != nil {
			return err
		}
	}
	notes, err := s.write(plan)
	if err != nil {
		return err
	}
	return s.finish(plan, notes, format)
}

// checks runs before any question: whatever can fail without the answers
// fails here.
func (s *sbxSetup) checks(ctx context.Context) error {
	s.ui.section("Checks")
	s.secrets = map[string]bool{}
	switch {
	case s.a.inContainer():
		s.ui.note("jira runs in the Docker wrapper's container: the sbx steps run on your machine afterwards.")
	case s.f.skipChecks:
		s.ui.warn("checks skipped (--skip-checks): only the files are written")
	default:
		if _, err := sbxLookPath("sbx"); err != nil {
			return s.fail(clierr.LayerConfig, "sbx_not_found", errors.New("sbx (Docker Sandboxes) is not installed"),
				"install it (https://docs.docker.com/ai/sandboxes/), or pass --skip-checks to only write the files")
		}
		out, err := sbxRun(ctx, "", false, "secret", "ls")
		if err != nil {
			return s.fail(clierr.LayerConfig, "sbx_failed", fmt.Errorf("sbx secret ls failed: %s", strings.TrimSpace(string(out))), "is sbx signed in? run 'sbx login'")
		}
		for _, line := range strings.Split(string(out), "\n") {
			if f := strings.Fields(line); len(f) > 0 && sbx.ValidSecretName(f[0]) == nil {
				s.secrets[f[0]] = true
			}
		}
		s.haveSbx = true
		s.ui.ok("sbx is installed; secrets: " + orNone(sortedKeys(s.secrets)))
	}
	if s.a.dryRun {
		return nil
	}
	var err error
	if s.tmp, err = os.MkdirTemp("", "jira-setup-sbx-"); err != nil {
		return err
	}
	source := "auto"
	if s.f.binaryFile != "" {
		source = sbx.SourceFile
	}
	s.bin, s.binSrc, err = sbx.GetBinary(ctx, sbx.BinaryRequest{Source: source, Arch: runtime.GOARCH, Version: s.a.Version,
		Clone: s.f.sourceDir, File: absIfSet(s.f.binaryFile), Dir: s.tmp, Log: s.ui.note})
	if err != nil {
		return s.fail(clierr.LayerUsage, "no_linux_binary", err, "run it from a jira-cli clone with Go installed, use a released jira, or pass --binary-file")
	}
	s.ui.ok(fmt.Sprintf("jira for linux/%s %s", runtime.GOARCH, s.ui.dim("("+s.binSrc+")")))
	return nil
}

// applyDefaults fills what no flag set, from this project's previous setup
// or the last setup of any project; it reports whether there were any.
func (s *sbxSetup) applyDefaults() bool {
	o := s.o()
	d := sbx.LoadDefaults(o.Project, o.Settings)
	if !s.set("agent") && d.Agent != "" {
		o.Agent, o.AgentName = d.Agent, d.AgentName
	}
	for _, v := range []struct {
		flag string
		dst  *string
		val  string
	}{{"image", &o.Image, d.Image}, {"secret", &o.Secret, d.Secret}} {
		if !s.set(v.flag) && v.val != "" {
			*v.dst = v.val
		}
	}
	if d.ReadOnly != nil && !s.set("allow-writes") {
		o.ReadOnly = *d.ReadOnly
	}
	if d.Skill != nil && !s.set("no-skill") {
		o.Skill = *d.Skill
	}
	if !s.set("name") {
		if d.Project {
			o.Name = d.Name // keep the existing sandbox's name, even sbx's default
		} else {
			s.nameDefaulted = true
		}
	}
	s.refreshName()
	if d.From != "" {
		s.ui.note("Defaults from " + d.From)
	}
	return d.From != ""
}

// agentName is the sbx agent name the answers lead to.
func (s *sbxSetup) agentName() string {
	o := s.o()
	switch {
	case o.AgentName != "":
		return o.AgentName
	case sbx.IsKitRef(o.Agent):
		return sbx.AgentFromKit(o.Agent)
	}
	return o.Agent
}

func (s *sbxSetup) refreshName() {
	if s.nameDefaulted {
		s.o().Name = sbx.DefaultName(s.agentName(), s.o().Project)
	}
}

func (s *sbxSetup) baseURL() string {
	if s.o().BaseURL != "" {
		return s.o().BaseURL
	}
	return sbx.BaseURLFromConfig(s.o().Settings)
}

func (s *sbxSetup) checkURL(ctx context.Context) func(string) error {
	return func(v string) error {
		if _, _, err := sbx.ParseBaseURL(v); err != nil || s.f.skipChecks {
			return err
		}
		return sbx.CheckReachable(ctx, v)
	}
}

// ask runs the guided questions; each answer is checked when given.
func (s *sbxSetup) ask(ctx context.Context) error {
	o, ui := s.o(), s.ui
	q := &form{p: newPrompter(ctx, s.a.In, ui), ui: ui}
	ui.note("Enter keeps the value in [brackets], '-' clears an optional one, Ctrl+C quits (nothing is written before you confirm).")

	ui.section("Project")
	if s.a.inContainer() && s.set("project") { // the wrapper asked on the host
		ui.kv("project", o.Project)
	} else {
		q.text(&o.Project, "Project the agent works in (mounted read/write)", func(v string) error { return sbx.ValidDir(absPath(v)) })
		o.Project = absPath(o.Project)
	}
	if b, err := os.ReadFile(filepath.Join(o.Project, "sbxenv.yaml")); q.err == nil && err == nil && !sbx.IsGenerated(b) && !o.Force {
		ui.warn("this project has an sbxenv.yaml that jira-cli did not generate")
		q.yesno(&o.Force, "Replace it")
		if q.err == nil && !o.Force {
			return clierr.New(clierr.LayerSafety, "confirmation_declined", "aborted; nothing was written")
		}
	}
	if q.err != nil {
		return q.err
	}
	known := s.applyDefaults()
	o.BaseURL = s.baseURL()

	if known && s.checkURL(ctx)(o.BaseURL) == nil {
		s.summary()
		same := true
		if q.yesno(&same, "Use these settings"); same {
			q.yesno(&s.f.run, "Start the sandbox when done (sbx env run)")
			return q.err
		}
	}

	ui.section("Jira")
	q.text(&o.BaseURL, "Jira base URL (https://, with the context path if any)", s.checkURL(ctx))

	ui.section("Agent and sandbox")
	ui.note("A built-in sbx agent (e.g. opencode) or an agent kit reference (registry/repo:tag).")
	ui.note("If sbx knows the kit under another name, it is used automatically.")
	before := o.Agent
	q.text(&o.Agent, "Agent", func(v string) error {
		if sbx.IsKitRef(v) {
			return sbx.ValidRef(v)
		}
		return sbx.ValidName(v)
	})
	if o.Agent != before {
		o.AgentName = ""
	}
	q.text(&o.Image, "Sandbox image (empty = the agent's default)", optional(sbx.ValidRef))
	s.refreshName()
	if q.err == nil {
		ui.note("'-' uses sbx's own default, <agent>-<folder>, which 'sbx run' also gives a sandbox there.")
	}
	q.text(&o.Name, "Sandbox name", optional(sbx.ValidName))
	q.yesno(&o.ReadOnly, "Read-only (the agent cannot change anything in Jira)")
	if q.err != nil {
		return q.err
	}
	s.summary()
	ok := true
	if !s.a.yes {
		q.yesno(&ok, "Proceed")
	}
	if q.err == nil && !ok {
		return clierr.New(clierr.LayerSafety, "confirmation_declined", "aborted; nothing was written")
	}
	q.yesno(&s.f.run, "Start the sandbox when done (sbx env run)")
	return q.err
}

func (s *sbxSetup) summary() {
	o, ui := s.o(), s.ui
	ui.section("Summary")
	ui.kv("project", o.Project)
	ui.kv("jira", o.BaseURL)
	ui.kv("agent", o.Agent+map[bool]string{true: ui.dim(" (sbx name: " + s.agentName() + ")")}[sbx.IsKitRef(o.Agent)])
	ui.kv("image", or(o.Image, "agent default"))
	ui.kv("name", or(o.Name, "sbx default"))
	ui.kv("read-only", map[bool]string{true: "yes", false: "no"}[o.ReadOnly])
	ui.kv("token", fmt.Sprintf("sbx secret %q", o.Secret))
	ui.println("")
}

// validate lets sbx check the complete environment in a scratch folder
// before the project is touched; an agent kit name sbx reports is taken
// over and the check repeated once.
func (s *sbxSetup) validate(ctx context.Context, plan *sbx.Plan) error {
	s.ui.section("Checking with sbx")
	if err := os.MkdirAll(plan.Settings, 0o755); err != nil { // the environment mounts it
		return err
	}
	for attempt := 0; ; attempt++ {
		scratch := *plan
		dir := filepath.Join(s.tmp, fmt.Sprint("plan-", attempt))
		scratch.KitDir, scratch.EnvFile = filepath.Join(dir, ".sbx", "jira-cli"), filepath.Join(dir, "sbxenv.yaml")
		if err := scratch.WriteKit(runtime.GOARCH, s.bin, s.a.Version); err != nil {
			return err
		}
		if err := scratch.WriteEnvFile(); err != nil {
			return err
		}
		out, err := sbxRun(ctx, dir, false, "env", "plan")
		if err == nil {
			s.ui.ok("sbx accepts the environment (agent " + plan.AgentName + ")")
			return nil
		}
		if name, ok := sbx.AgentNameFromSbx(out); ok && attempt == 0 && name != plan.AgentName {
			s.ui.warn(fmt.Sprintf("sbx names the agent kit %q: using it", name))
			plan.AgentName, s.o().AgentName = name, name
			if s.nameDefaulted {
				s.refreshName()
				plan.Name = s.o().Name
			}
			continue
		}
		s.ui.warn("sbx rejected the environment; nothing was written. sbx said:")
		for _, l := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			s.ui.println("    " + l)
		}
		first, _, _ := strings.Cut(strings.TrimSpace(string(out)), "\n")
		return s.fail(clierr.LayerConfig, "sbx_rejected", errors.New("sbx rejected the environment: "+first),
			"fix what it refers to and run jira setup-sbx again; your answers are offered as defaults")
	}
}

// ensureSecret makes sure the PAT is an sbx secret; sbx prompts for it, so
// it never passes through jira-cli.
func (s *sbxSetup) ensureSecret(ctx context.Context, secret string) error {
	if s.secrets[secret] {
		return nil
	}
	if !s.guided && !s.a.IsTerminal() {
		return s.fail(clierr.LayerCredentials, "sbx_secret_missing", fmt.Errorf("the sbx secret %s does not exist", secret),
			"run 'sbx secret set "+secret+"' in a terminal (it prompts for the PAT), then run this again")
	}
	s.ui.section("Jira personal access token")
	s.ui.note(fmt.Sprintf("Storing it as sbx secret %q: sbx prompts for it, and it stays on this machine.", secret))
	if _, err := sbxRun(ctx, "", true, "secret", "set", secret); err != nil {
		return s.fail(clierr.LayerCredentials, "sbx_secret_failed", fmt.Errorf("sbx secret set %s failed: %v", secret, err), "")
	}
	s.secrets[secret] = true
	s.ui.ok("sbx secret " + secret + " stored")
	return nil
}

func (s *sbxSetup) write(plan *sbx.Plan) ([]sbx.Note, error) {
	s.ui.section("Writing " + plan.Project)
	if err := plan.WriteKit(runtime.GOARCH, s.bin, s.a.Version); err != nil {
		return nil, err
	}
	notes := []sbx.Note{{Text: "kit " + plan.KitDir}}
	more, err := plan.WriteSettings()
	if err != nil {
		return nil, err
	}
	notes = append(notes, more...)
	if plan.Skill {
		sub, _ := fs.Sub(skills.FS, "jira")
		n, err := plan.WriteSkill(sub)
		if err != nil {
			return nil, err
		}
		notes = append(notes, n)
	}
	if err := plan.WriteEnvFile(); err != nil {
		return nil, err
	}
	notes = append(notes, sbx.Note{Text: "env file " + plan.EnvFile})
	if err := plan.SaveDefaults(); err != nil {
		notes = append(notes, sbx.Note{Warn: true, Text: "defaults not saved: " + err.Error()})
	}
	for _, n := range notes {
		if n.Warn {
			s.ui.warn(n.Text)
		} else {
			s.ui.ok(n.Text)
		}
	}
	return notes, nil
}

func (s *sbxSetup) finish(plan *sbx.Plan, notes []sbx.Note, format output.Format) error {
	ui := s.ui
	running := s.haveSbx && s.f.run
	ui.section("Next steps")
	switch {
	case s.a.inContainer():
		ui.note("jira ran in a container: the jira wrapper now checks the sbx secret and the environment on your machine.")
	case !s.haveSbx:
		ui.note("Not checked with sbx (--skip-checks).")
	case running:
		ui.note("Starting the sandbox now. Once it is up:")
	}
	steps := sbxNextSteps(plan, s.secrets[plan.Secret], running)
	var cmds []string
	for i, st := range steps {
		ui.println(fmt.Sprintf("  %s %s", ui.cyan(fmt.Sprintf("%d.", i+1)), st.what))
		for _, c := range st.cmds {
			ui.println("       " + ui.cmd(c))
			cmds = append(cmds, c)
		}
	}
	ui.println("")
	// The guided run is for people; scripts (flags or -o) get the result.
	if !s.guided || s.set("output") {
		texts := make([]string, len(notes))
		for i, n := range notes {
			texts[i] = n.Text
		}
		if err := output.Write(s.a.Out, map[string]any{"project": plan.Project, "env_file": plan.EnvFile, "agent": plan.AgentName,
			"name": plan.Name, "binary_source": s.binSrc, "jira_host": plan.Host, "secret": plan.Secret,
			"credential_env": plan.CredEnv, "checked_with_sbx": s.haveSbx, "notes": texts, "next": cmds}, format); err != nil {
			return err
		}
	}
	if running {
		if err := sbxHandOver(plan.Project, "env", "run"); err != nil {
			return s.fail(clierr.LayerUsage, "sbx_run_failed", fmt.Errorf("sbx env run failed: %v", err), "")
		}
	}
	return nil
}

type sbxStep struct {
	what string
	cmds []string
}

// sbxNextSteps is what to run after setup-sbx, on the host.
func sbxNextSteps(p *sbx.Plan, secretStored, running bool) []sbxStep {
	cd := "cd " + shellQuote(p.Project) + " && "
	var steps []sbxStep
	if !secretStored {
		steps = append(steps, sbxStep{"Store the Jira PAT, if 'sbx secret ls' does not list " + p.Secret + " (sbx prompts for it):",
			[]string{"sbx secret ls", "sbx secret set " + p.Secret}})
	}
	if !running {
		steps = append(steps, sbxStep{"Start the sandbox" + map[bool]string{true: " " + p.Name}[p.Name != ""] +
			". On the first start sbx asks you to approve egress to " + p.Host + ", the secret " + p.Secret +
			" for that host and the read-only settings mount:", []string{cd + "sbx env run"}})
	}
	return append(steps,
		sbxStep{"Check jira in it (from another terminal): credentials env:" + p.CredEnv + ", authentication ok:",
			[]string{cd + "sbx env exec -- bash -lc 'jira doctor'"}},
		sbxStep{"Ask the agent, e.g. \"list my 5 most recently updated Jira issues\".", nil},
		sbxStep{"If the sandbox does not start, look at the plan and at existing sandboxes (a sandbox with the same name: sbx rm NAME):",
			[]string{cd + "sbx env plan", "sbx ls", "sbx diagnose"}},
	)
}

// form asks questions until the first error (Ctrl+C, end of input), which
// it keeps in err, so a sequence of questions needs one error check.
type form struct {
	p   *prompter
	ui  *sbxUI
	err error
}

// text asks until validate (nil: anything) accepts the answer.
func (f *form) text(dst *string, q string, validate func(string) error) {
	for f.err == nil {
		v, err := f.p.ask(q, *dst)
		if f.err = err; err != nil {
			return
		}
		if validate != nil {
			if verr := validate(v); verr != nil {
				f.ui.warn(verr.Error())
				continue
			}
		}
		*dst = v
		return
	}
}

func (f *form) yesno(dst *bool, q string) {
	if f.err == nil {
		*dst, f.err = f.p.yn(q, *dst)
	}
}

func optional(check func(string) error) func(string) error {
	return func(v string) error {
		if v == "" {
			return nil
		}
		return check(v)
	}
}

// prompter asks on stderr and reads answers in a goroutine, so Ctrl+C (a
// cancelled ctx) ends a prompt at once instead of waiting for Enter.
type prompter struct {
	ctx   context.Context
	lines chan string
	ui    *sbxUI
}

func newPrompter(ctx context.Context, r io.Reader, ui *sbxUI) *prompter {
	p := &prompter{ctx: ctx, lines: make(chan string), ui: ui}
	go func() {
		defer close(p.lines) // later prompts see the end of input
		br := bufio.NewReader(r)
		for {
			line, err := br.ReadString('\n')
			if line == "" && err != nil {
				return
			}
			select {
			case p.lines <- line:
			case <-ctx.Done():
				return
			}
		}
	}()
	return p
}

// ask shows cur as the default: Enter keeps it, "-" clears it.
func (p *prompter) ask(q, cur string) (string, error) {
	fmt.Fprint(p.ui.w, p.ui.question(q, cur))
	select {
	case <-p.ctx.Done():
		fmt.Fprintln(p.ui.w)
		return "", clierr.Interrupted()
	case line, ok := <-p.lines:
		if !ok {
			return "", clierr.New(clierr.LayerUsage, "no_answer", "no answer (end of input)")
		}
		switch v := strings.TrimSpace(line); v {
		case "":
			return cur, nil
		case "-":
			return "", nil
		default:
			return v, nil
		}
	}
}

func (p *prompter) yn(q string, cur bool) (bool, error) {
	hint := map[bool]string{true: "Y/n", false: "y/N"}[cur]
	for {
		v, err := p.ask(q+" "+p.ui.dim("["+hint+"]"), "")
		if err != nil {
			return false, err
		}
		switch strings.ToLower(v) {
		case "":
			return cur, nil
		case "y", "yes":
			return true, nil
		case "n", "no":
			return false, nil
		}
	}
}

// inContainer reports whether jira runs in the Docker wrapper's container,
// where sbx is not available and only mounted host paths exist.
func (a *App) inContainer() bool { return a.Getenv("JIRA_CLI_CONTAINER") == "1" }

func expandHome(p string) string {
	if p == "~" || strings.HasPrefix(p, "~/") {
		if home, err := os.UserHomeDir(); err == nil {
			return filepath.Join(home, strings.TrimPrefix(p, "~"))
		}
	}
	return p
}

func absPath(p string) string {
	if a, err := filepath.Abs(expandHome(p)); err == nil {
		return a
	}
	return p
}

func absIfSet(p string) string {
	if p == "" {
		return ""
	}
	return absPath(p)
}

// shellQuote quotes s for a POSIX shell when it needs it.
func shellQuote(s string) string {
	if s != "" && strings.Trim(s, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._/-~+:@%=,") == "" {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func or(v, def string) string {
	if v == "" {
		return def
	}
	return v
}

func sortedKeys(m map[string]bool) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func orNone(v []string) string { return or(strings.Join(v, ", "), "none yet") }

package sbx

import "text/template"

// Values interpolated into these templates are validated in NewPlan to
// plain character sets, so they need no YAML or shell quoting.

var funcs = template.FuncMap{
	// code wraps s in backticks (raw strings cannot contain them).
	"code": func(s string) string { return "`" + s + "`" },
}

func mustTemplate(name, text string) *template.Template {
	return template.Must(template.New(name).Funcs(funcs).Parse(text))
}

const dockerfile = `# syntax=docker/dockerfile:1
# Overlay for the jira-cli sbx kit: a static binary and a profile hook.
# /usr/bin is on PATH in every agent shell (custom images may leave out
# /usr/local/bin); installing here needs nothing at sandbox start.
# Built by sbx on create; the context is this directory.
FROM scratch
ARG TARGETARCH
COPY --chmod=0755 bin/jira-${TARGETARCH} /usr/bin/jira
COPY --chmod=0644 profile.sh /etc/profile.d/jira-cli.sh
`

var profileTmpl = mustTemplate("profile", `# Installed by the jira-cli sbx kit as /etc/profile.d/jira-cli.sh.
# Login shells source the editable host file, mounted at the same path.
if [ -r {{.BashrcFile}} ] && [ -z "${JIRA_CLI_BASHRC_LOADED:-}" ]; then
  JIRA_CLI_BASHRC_LOADED=1
  . {{.BashrcFile}}
fi
`)

var kitTmpl = mustTemplate("kit", `# syntax=docker/sandbox-kit:3
# Generated by jira setup-sbx. Re-run it instead of editing this file.
schemaVersion: "3"
displayName: jira-cli
description: >-
  jira-cli for Jira Data Center at {{.Host}}, with the personal access token
  held by sbx (service "{{.Service}}") and injected by the sandbox proxy.
sourceUrl: https://github.com/Personal-Stack/jira-cli
licenses: [Apache-2.0]

kind: mixin
version: "{{.KitVersion}}"
provides: ["jira-cli@{{.KitVersion}}"]
dockerfile: jira-cli.dockerfile

capabilities:
  - type: com.docker.sandbox/network-policy@1
    config:
      runtime:
        allow:
          - {{.Host}}:{{.Port}}

  # The PAT stays on the host. {{.CredEnv}} holds a sentinel; the proxy sets
  # the real "Authorization: Bearer <PAT>" on requests to {{.Host}}.
  - type: com.docker.sandbox/credential@1
    description: Jira personal access token for jira-cli
    config:
      service: {{.Service}}
      phase: runtime
      apiKey:
        name: {{.CredEnv}}
        proxyManaged: true
        inject:
          - {domain: {{.Host}}, header: Authorization, format: "Bearer %s"}

  - type: com.docker.sandbox/lifecycle@1
    config:
      startup:
        # Interactive bash shells source the editable host file (login shells
        # get it from /etc/profile.d/jira-cli.sh). Idempotent, and it never
        # fails: a failing startup hook aborts the whole sandbox start.
        - command:
            - sh
            - -c
            - >-
              { grep -qsF '{{.BashrcFile}}' /etc/bash.bashrc ||
              printf '\n# jira-cli sbx kit\n[ -r {{.BashrcFile}} ] && . {{.BashrcFile}}\n' >> /etc/bash.bashrc; } 2>/dev/null || true
          user: "0"
          description: Source {{.BashrcFile}} from interactive bash shells (best effort; never fails the start)

  - type: com.docker.sandbox/agent-context@1
    optional: true
    config: &agent-context
      content: |
        ## Jira (jira-cli)

        {{code "jira"}} is on PATH (/usr/bin/jira; use the full path if a shell cannot
        find it). Use the {{code "jira"}} skill
        (.opencode/skills/jira): discover commands with {{code "jira commands list"}} and
        {{code "jira commands describe <group> <command>"}} instead of guessing them.

        - Authentication is proxy-managed: {{code .CredEnv}} is a sentinel and the
          real token is injected on requests to {{.Host}}. Never print or copy
          it, and do not run {{code "jira auth login"}}.
        - {{.ModeText}}
        - Keep queries small: --max-results 50 or less; with --all add --max-pages 3.
        - The configuration is read-only at {{.Settings}}; changes are made by
          the user on the host.

  - type: com.docker.sandbox/agent-context@2
    optional: true
    config: *agent-context
`)


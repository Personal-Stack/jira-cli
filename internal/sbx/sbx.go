// Package sbx generates a Docker Sandboxes (sbx) environment in which an AI
// agent can use jira-cli while the Jira personal access token stays on the
// host:
//
//   - <project>/.sbx/jira-cli/: a local sbx kit (mixin) with the linux jira
//     binary, an egress rule for the Jira host and a proxy-managed
//     credential (the sandbox only sees a sentinel; the sbx proxy sets the
//     real Authorization header);
//   - <project>/sbxenv.yaml: the environment `sbx env run` reads;
//   - <project>/.opencode/skills/jira: the agent skill;
//   - <settings>/config.yaml and bashrc: created once, mounted read-only at
//     the same path inside the sandbox.
//
// See docs/sandbox.md.
package sbx

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"

	"github.com/personal-stack/jira-cli/internal/credentials"
)

// GeneratedMarker starts every sbxenv.yaml this package writes; other files
// are only replaced with Force.
const GeneratedMarker = "# generated by jira setup-sbx"

var markers = []string{GeneratedMarker, "# generated by jira-cli scripts/sbx-setup.sh"}

// Options are the user's choices.
type Options struct {
	Project  string // workspace the agent works in; sbxenv.yaml goes here
	Settings string // host folder with config.yaml and bashrc, outside Project
	BaseURL  string // Jira base URL; empty: from <Settings>/config.yaml

	// Agent is a built-in sbx agent ("opencode") or an agent kit reference
	// ("registry/team/opencode:2.1"). AgentName is the name sbx knows the
	// kit by, when it differs from the reference's last path segment.
	Agent, AgentName string

	Image  string // sandbox image (sandboxOptions.template); empty: the agent's
	Name   string // sandbox name; empty: sbx's default
	Secret string // sbx secret holding the PAT

	ReadOnly bool // read_only in config.yaml and JIRA_READ_ONLY=1
	Skill    bool // install the skill as <Project>/.opencode/skills/jira
	Force    bool // replace a foreign sbxenv.yaml and an edited skill
}

// Plan is validated Options plus what follows from them.
type Plan struct {
	Options
	AgentKit string // the kit reference, or "" for a built-in agent
	Host     string
	Port     int
	CredRef  string // credential_ref in config.yaml
	CredEnv  string // JIRA_CREDENTIAL_<REF>, the sentinel the sandbox sees

	KitDir, EnvFile, ConfigFile, BashrcFile, SkillDir string
}

// IsKitRef reports whether an agent answer is a kit reference, not a name.
func IsKitRef(agent string) bool { return strings.ContainsAny(agent, "/:@") }

// AgentFromKit is the name sbx usually gives a kit: the last path segment
// without tag or digest (sbx/opencode:1.2@sha256:... -> opencode).
func AgentFromKit(ref string) string {
	h, _, _ := strings.Cut(ref, "@")
	h = h[strings.LastIndex(h, "/")+1:]
	h, _, _ = strings.Cut(h, ":")
	return h
}

// NewPlan validates o; paths must be absolute.
func NewPlan(o Options) (*Plan, error) {
	p := &Plan{Options: o, CredRef: "jira-prod"}
	p.Project, p.Settings = filepath.Clean(o.Project), filepath.Clean(o.Settings)
	if err := ValidDir(p.Project); err != nil {
		return nil, err
	}
	if err := ValidSettingsPath(p.Settings); err != nil {
		return nil, err
	}
	if p.Settings == p.Project || strings.HasPrefix(p.Settings+"/", p.Project+"/") {
		return nil, fmt.Errorf("the settings folder must be outside the project (%s is inside %s)", p.Settings, p.Project)
	}
	p.ConfigFile = filepath.Join(p.Settings, "config.yaml")
	p.BashrcFile = filepath.Join(p.Settings, "bashrc")
	p.KitDir = filepath.Join(p.Project, ".sbx", "jira-cli")
	p.EnvFile = filepath.Join(p.Project, "sbxenv.yaml")
	p.SkillDir = filepath.Join(p.Project, ".opencode", "skills", "jira")

	cfg := readConfig(p.ConfigFile)
	if cfg.credRef != "" {
		p.CredRef = cfg.credRef // the existing config decides; the kit must match it
	}
	if p.BaseURL == "" {
		if p.BaseURL = cfg.baseURL; p.BaseURL == "" {
			return nil, errors.New("the Jira base URL is required (no config.yaml with base_url yet)")
		}
	}
	var err error
	if p.Host, p.Port, err = ParseBaseURL(p.BaseURL); err != nil {
		return nil, err
	}

	if IsKitRef(o.Agent) {
		if err := ValidRef(o.Agent); err != nil {
			return nil, err
		}
		p.AgentKit = o.Agent
		if p.AgentName == "" {
			p.AgentName = AgentFromKit(o.Agent)
		}
	} else {
		p.AgentName = o.Agent
	}
	checks := []error{ValidName(p.AgentName), ValidSecretName(o.Secret), ValidName(p.CredRef)}
	if o.Image != "" {
		checks = append(checks, ValidRef(o.Image))
	}
	if o.Name != "" {
		checks = append(checks, ValidName(o.Name))
	}
	if err := errors.Join(checks...); err != nil {
		return nil, err
	}
	p.CredEnv = credentials.EnvName(p.CredRef)
	return p, nil
}

// IsGenerated reports whether an sbxenv.yaml was written by jira-cli.
func IsGenerated(b []byte) bool {
	for _, m := range markers {
		if bytes.HasPrefix(b, []byte(m)) {
			return true
		}
	}
	return false
}

// CheckEnvFile refuses to replace a foreign sbxenv.yaml unless Force.
func (p *Plan) CheckEnvFile() error {
	b, err := os.ReadFile(p.EnvFile)
	if err != nil || IsGenerated(b) || p.Force {
		return nil
	}
	return fmt.Errorf("%s exists and was not generated by jira-cli; move it away or use --force to replace it", p.EnvFile)
}

var semverRe = regexp.MustCompile(`^v?(\d+\.\d+\.\d+)`)

// KitVersion turns a CLI version into the kit's semver (dev builds: 0.0.0).
func KitVersion(v string) string {
	if m := semverRe.FindStringSubmatch(v); m != nil {
		return m[1]
	}
	return "0.0.0"
}

// WriteKit writes the kit with the linux jira binary for arch.
func (p *Plan) WriteKit(arch, binary, version string) error {
	if err := os.RemoveAll(p.KitDir); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(p.KitDir, "bin"), 0o755); err != nil {
		return err
	}
	if err := copyFile(binary, filepath.Join(p.KitDir, "bin", "jira-"+arch), 0o755); err != nil {
		return err
	}
	kit, err := render(kitTmpl, struct {
		*Plan
		KitVersion string
	}{p, KitVersion(version)})
	if err != nil {
		return err
	}
	return writeFiles(p.KitDir, map[string]string{".gitignore": "bin/\n", "jira-cli.dockerfile": dockerfile, "jira-cli.yaml": kit})
}

// EnvFileContent renders sbxenv.yaml.
func (p *Plan) EnvFileContent() (string, error) { return render(envTmpl, p) }

// WriteEnvFile writes sbxenv.yaml (CheckEnvFile first).
func (p *Plan) WriteEnvFile() error {
	s, err := p.EnvFileContent()
	if err != nil {
		return err
	}
	return os.WriteFile(p.EnvFile, []byte(s), 0o644)
}

// Note is one line of what a write did; Warn marks something to look at.
type Note struct {
	Text string
	Warn bool
}

// WriteSettings creates config.yaml and bashrc when missing; existing files
// are the user's and are never overwritten.
func (p *Plan) WriteSettings() ([]Note, error) {
	if err := os.MkdirAll(p.Settings, 0o755); err != nil {
		return nil, err
	}
	var notes []Note
	for _, f := range []struct {
		path string
		tmpl *template.Template
	}{{p.ConfigFile, configTmpl}, {p.BashrcFile, bashrcTmpl}} {
		if _, err := os.Stat(f.path); err == nil {
			notes = append(notes, Note{Text: "kept " + f.path})
			continue
		}
		s, err := render(f.tmpl, p)
		if err != nil {
			return nil, err
		}
		if err := os.WriteFile(f.path, []byte(s), 0o644); err != nil {
			return nil, err
		}
		notes = append(notes, Note{Text: "created " + f.path})
	}
	if b, _ := os.ReadFile(p.ConfigFile); bytes.Contains(b, []byte("/etc/jira-cli/")) {
		notes = append(notes, Note{Warn: true, Text: p.ConfigFile + " refers to /etc/jira-cli/, which does not exist in the sandbox"})
	}
	return notes, nil
}

// WriteSkill installs skill (the skill directory's contents) at SkillDir.
// Local edits are kept unless Force.
func (p *Plan) WriteSkill(skill fs.FS) (Note, error) {
	if _, err := os.Stat(p.SkillDir); err == nil && !p.Force {
		if same, err := sameTree(skill, p.SkillDir); err != nil || !same {
			return Note{Warn: true, Text: p.SkillDir + " has local edits and was kept (--force replaces it)"}, err
		}
	}
	if err := os.RemoveAll(p.SkillDir); err != nil {
		return Note{}, err
	}
	err := fs.WalkDir(skill, ".", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		dst := filepath.Join(p.SkillDir, filepath.FromSlash(path))
		if d.IsDir() {
			return os.MkdirAll(dst, 0o755)
		}
		b, err := fs.ReadFile(skill, path)
		if err != nil {
			return err
		}
		mode := os.FileMode(0o644)
		if strings.HasSuffix(path, ".sh") {
			mode = 0o755
		}
		return os.WriteFile(dst, b, mode)
	})
	return Note{Text: "skill " + p.SkillDir}, err
}

// sameTree reports whether dir holds exactly the files of a.
func sameTree(a fs.FS, dir string) (bool, error) {
	want := map[string][]byte{}
	if err := fs.WalkDir(a, ".", func(path string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			want[path], err = fs.ReadFile(a, path)
		}
		return err
	}); err != nil {
		return false, err
	}
	same := true
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(dir, path)
		rel = filepath.ToSlash(rel)
		got, err := os.ReadFile(path)
		if w, ok := want[rel]; err != nil || !ok || !bytes.Equal(w, got) {
			same = false
		}
		delete(want, rel)
		return nil
	})
	return same && len(want) == 0, err
}

func writeFiles(dir string, files map[string]string) error {
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func copyFile(src, dst string, mode os.FileMode) error {
	b, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	if err := os.WriteFile(dst, b, mode); err != nil {
		return err
	}
	return os.Chmod(dst, mode)
}

func render(t *template.Template, data any) (string, error) {
	var b strings.Builder
	err := t.Execute(&b, data)
	return b.String(), err
}

// Package sbx generates a Docker Sandboxes (sbx) environment in which an AI
// agent can use jira-cli while the Jira personal access token stays on the
// host:
//
//   - <project>/tmp/.sbx/jira-cli/ (KitPath): a local sbx kit (mixin) with the linux jira
//     binary, an egress rule for the Jira host and a proxy-managed
//     credential (the sandbox only sees a sentinel; the sbx proxy sets the
//     real Authorization header);
//   - <project>/sbxenv.yaml: the environment `sbx env run` reads;
//   - <project>/.opencode/skills/jira (SkillsPath): the agent skill;
//   - <settings>/config.yaml and bashrc: created once, mounted read-only at
//     the same path inside the sandbox.
//
// See docs/sandbox.md.
package sbx

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"

	"github.com/personal-stack/jira-cli/internal/credentials"
)

// GeneratedMarker starts every sbxenv.yaml this package writes; other files
// are only replaced with Force.
const GeneratedMarker = "# generated by jiracli setup-sbx"

// DefaultKitPath is where the kit goes in the project (Options.KitPath);
// earlier versions used legacyKitPath.
const (
	DefaultKitPath = "tmp/.sbx/jira-cli"
	kitMarker      = "Generated by jiracli setup-sbx"
)

// DefaultSkillsPath is the skills folder, relative to the project, that the
// jira skill goes into (Options.SkillsPath); OpenCode reads project skills
// from here.
const DefaultSkillsPath = ".opencode/skills"

// skillName is the skill's folder inside the skills folder.
const skillName = "jira"

// isJiraKit reports whether the kits entry k (a ./path) of project's
// sbxenv.yaml is a kit this package generated.
func isJiraKit(project, k string) bool {
	if !strings.HasPrefix(k, "./") {
		return false
	}
	b, err := os.ReadFile(filepath.Join(project, filepath.FromSlash(k), "jira-cli.yaml"))
	return err == nil && bytes.Contains(b, []byte(kitMarker))
}

var markers = []string{GeneratedMarker, "# generated by jira-cli scripts/sbx-setup.sh"}

// Options are the user's choices.
type Options struct {
	Project  string // workspace the agent works in; sbxenv.yaml goes here
	Settings string // host folder with config.yaml and bashrc, outside Project
	BaseURL  string // Jira base URL; empty: from <Settings>/config.yaml

	// Agent is the sbx agent's name ("opencode", "devex-opencode"). The
	// environment composes no other kit than jira-cli's.
	Agent string

	// KitPath is the kit's folder, relative to Project (DefaultKitPath);
	// PrevKitPath is where an earlier setup put it (removed when it moved).
	KitPath, PrevKitPath string

	Name   string // sandbox name; empty: sbx's default
	Secret string // sbx secret holding the PAT

	ReadOnly bool // read_only in config.yaml and JIRA_READ_ONLY=1
	Skill    bool // install the skill as <Project>/<SkillsPath>/jira

	// SkillsPath is the skills folder, relative to Project
	// (DefaultSkillsPath); PrevSkillsPath is where an earlier setup put the
	// skill (an unedited copy there is removed when it moved).
	SkillsPath, PrevSkillsPath string

	Force bool // replace a foreign sbxenv.yaml and an edited skill
}

// Plan is validated Options plus what follows from them.
type Plan struct {
	Options
	Host    string
	Port    int
	CredRef string // credential_ref in config.yaml
	CredEnv string // JIRA_CREDENTIAL_<REF>, the sentinel the sandbox sees

	KitDir, EnvFile, ConfigFile, BashrcFile, SkillDir string
}

// KitRef is the kit as sbxenv.yaml lists it.
func (p *Plan) KitRef() string { return "./" + p.KitPath }

// BinPath is the jiracli binary inside the sandbox. The project is mounted at
// the same absolute path, so the kit's copy is there whether or not the
// kit's image layer was applied.
func (p *Plan) BinPath() string { return filepath.Join(p.KitDir, "bin", "jiracli") }

// SkillPath is the skill's folder relative to the project, as the agent
// instructions name it.
func (p *Plan) SkillPath() string { return p.SkillsPath + "/" + skillName }

// NewPlan validates o; paths must be absolute.
func NewPlan(o Options) (*Plan, error) {
	p := &Plan{Options: o, CredRef: "jira-prod"}
	p.Project, p.Settings = filepath.Clean(o.Project), filepath.Clean(o.Settings)
	if err := ValidDir(p.Project); err != nil {
		return nil, err
	}
	if err := ValidSettingsPath(p.Settings); err != nil {
		return nil, err
	}
	if p.Settings == p.Project || strings.HasPrefix(p.Settings+"/", p.Project+"/") {
		return nil, fmt.Errorf("the settings folder must be outside the project (%s is inside %s)", p.Settings, p.Project)
	}
	p.ConfigFile = filepath.Join(p.Settings, "config.yaml")
	p.BashrcFile = filepath.Join(p.Settings, "bashrc")
	if p.KitPath == "" {
		p.KitPath = DefaultKitPath
	}
	if err := ValidKitPath(p.KitPath); err != nil {
		return nil, err
	}
	p.KitDir = filepath.Join(p.Project, filepath.FromSlash(p.KitPath))
	p.EnvFile = filepath.Join(p.Project, "sbxenv.yaml")
	if p.SkillsPath == "" {
		p.SkillsPath = DefaultSkillsPath
	}
	if err := ValidSkillsPath(p.SkillsPath); err != nil {
		return nil, err
	}
	p.SkillDir = filepath.Join(p.Project, filepath.FromSlash(p.SkillsPath), skillName)

	cfg := readConfig(p.ConfigFile)
	if cfg.credRef != "" {
		p.CredRef = cfg.credRef // the existing config decides; the kit must match it
	}
	if p.BaseURL == "" {
		if p.BaseURL = cfg.baseURL; p.BaseURL == "" {
			return nil, errors.New("the Jira base URL is required (no config.yaml with base_url yet)")
		}
	}
	var err error
	if p.Host, p.Port, err = ParseBaseURL(p.BaseURL); err != nil {
		return nil, err
	}

	checks := []error{ValidAgent(o.Agent), ValidSecretName(o.Secret), ValidName(p.CredRef)}
	if o.Name != "" {
		checks = append(checks, ValidSandboxName(o.Name))
	}
	if err := errors.Join(checks...); err != nil {
		return nil, err
	}
	p.CredEnv = credentials.EnvName(p.CredRef)
	return p, nil
}

// IsGenerated reports whether an sbxenv.yaml was written by jira-cli.
func IsGenerated(b []byte) bool {
	for _, m := range markers {
		if bytes.HasPrefix(b, []byte(m)) {
			return true
		}
	}
	return false
}

// CheckEnvFile refuses to replace a foreign sbxenv.yaml unless Force.
func (p *Plan) CheckEnvFile() error {
	b, err := os.ReadFile(p.EnvFile)
	if err != nil || IsGenerated(b) || p.Force {
		return nil
	}
	return fmt.Errorf("%s exists and was not generated by jira-cli; move it away or use --force to replace it", p.EnvFile)
}

var semverRe = regexp.MustCompile(`^v?(\d+\.\d+\.\d+)`)

// KitVersion turns a CLI version into the kit's semver (dev builds: 0.0.0).
func KitVersion(v string) string {
	if m := semverRe.FindStringSubmatch(v); m != nil {
		return m[1]
	}
	return "0.0.0"
}

// WriteKit writes the kit with the linux jiracli binary.
func (p *Plan) WriteKit(binary, version string) error {
	if err := os.RemoveAll(p.KitDir); err != nil {
		return err
	}
	// A kit an earlier setup put elsewhere, if it is ours: no stale binary stays.
	for _, old := range []string{p.PrevKitPath, ".sbx/jira-cli", "temp/.sbx/jira-cli"} { // and earlier versions' places
		if old != "" && old != p.KitPath && isJiraKit(p.Project, "./"+old) {
			_ = os.RemoveAll(filepath.Join(p.Project, filepath.FromSlash(old)))
		}
	}
	if err := os.MkdirAll(filepath.Join(p.KitDir, "bin"), 0o755); err != nil {
		return err
	}
	if err := copyFile(binary, p.BinPath(), 0o755); err != nil {
		return err
	}
	kit, err := render(kitTmpl, struct {
		*Plan
		KitVersion string
	}{p, KitVersion(version)})
	if err != nil {
		return err
	}
	return writeFiles(p.KitDir, map[string]string{".gitignore": "bin/\n", "jira-cli.dockerfile": dockerfile, "jira-cli.yaml": kit})
}

// EnvFileContent renders sbxenv.yaml.
func (p *Plan) EnvFileContent() (string, error) { return render(envTmpl, p) }

// WriteEnvFile writes sbxenv.yaml (CheckEnvFile first).
func (p *Plan) WriteEnvFile() error {
	s, err := p.EnvFileContent()
	if err != nil {
		return err
	}
	return os.WriteFile(p.EnvFile, []byte(s), 0o644)
}

// Note is one line of what a write did; Warn marks something to look at.
type Note struct {
	Text string
	Warn bool
}

// WriteSettings creates config.yaml and bashrc when missing; existing files
// are the user's and are never overwritten.
func (p *Plan) WriteSettings() ([]Note, error) {
	if err := os.MkdirAll(p.Settings, 0o755); err != nil {
		return nil, err
	}
	var notes []Note
	for _, f := range []struct {
		path string
		tmpl *template.Template
	}{{p.ConfigFile, configTmpl}, {p.BashrcFile, bashrcTmpl}} {
		if _, err := os.Stat(f.path); err == nil {
			notes = append(notes, Note{Text: "kept " + f.path})
			continue
		}
		s, err := render(f.tmpl, p)
		if err != nil {
			return nil, err
		}
		if err := os.WriteFile(f.path, []byte(s), 0o644); err != nil {
			return nil, err
		}
		notes = append(notes, Note{Text: "created " + f.path})
	}
	if b, _ := os.ReadFile(p.ConfigFile); bytes.Contains(b, []byte("/etc/jira-cli/")) {
		notes = append(notes, Note{Warn: true, Text: p.ConfigFile + " refers to /etc/jira-cli/, which does not exist in the sandbox"})
	}
	return notes, nil
}

// WriteSkill installs skill (the skill directory's contents) at SkillDir,
// with a "This sandbox" section in SKILL.md saying where the binary and the
// configuration are. Local edits are kept unless Force.
func (p *Plan) WriteSkill(skill fs.FS) (Note, error) {
	files, err := p.skillFiles(skill)
	if err != nil {
		return Note{}, err
	}
	note := Note{Text: "skill " + p.SkillDir}
	// A copy an earlier setup put elsewhere goes, unless it was edited.
	for _, old := range []string{p.PrevSkillsPath, DefaultSkillsPath} {
		if old == "" || old == p.SkillsPath || ValidSkillsPath(old) != nil {
			continue
		}
		dir := filepath.Join(p.Project, filepath.FromSlash(old), skillName)
		if _, err := os.Stat(dir); err != nil {
			continue
		}
		if sameTree(files, dir) {
			_ = os.RemoveAll(dir)
		} else {
			note = Note{Warn: true, Text: "skill " + p.SkillDir + "; " + dir + " (edited or not jira-cli's) was kept: remove it if the agent should not see two jira skills"}
		}
	}
	if _, err := os.Stat(p.SkillDir); err == nil && !p.Force && !sameTree(files, p.SkillDir) {
		return Note{Warn: true, Text: p.SkillDir + " has local edits and was kept (--force replaces it)"}, nil
	}
	if err := os.RemoveAll(p.SkillDir); err != nil {
		return Note{}, err
	}
	for path, b := range files {
		dst := filepath.Join(p.SkillDir, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return Note{}, err
		}
		mode := os.FileMode(0o644)
		if strings.HasSuffix(path, ".sh") {
			mode = 0o755
		}
		if err := os.WriteFile(dst, b, mode); err != nil {
			return Note{}, err
		}
	}
	return note, nil
}

// skillFiles is the skill as installed: its files, with the sandbox section
// inserted after SKILL.md's title.
func (p *Plan) skillFiles(skill fs.FS) (map[string][]byte, error) {
	files := map[string][]byte{}
	err := fs.WalkDir(skill, ".", func(path string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			files[path], err = fs.ReadFile(skill, path)
		}
		return err
	})
	if err != nil {
		return nil, err
	}
	section, err := render(skillSectionTmpl, p)
	if err != nil {
		return nil, err
	}
	md := string(files["SKILL.md"])
	if i := strings.Index(md, "\n# "); i >= 0 {
		end := i + 1 + strings.Index(md[i+1:], "\n") + 1 // after the title line
		md = md[:end] + "\n" + section + md[end:]
	} else {
		md += "\n" + section
	}
	files["SKILL.md"] = []byte(md)
	return files, nil
}

// sameTree reports whether dir holds exactly files.
func sameTree(files map[string][]byte, dir string) bool {
	seen := 0
	same := true
	_ = filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(dir, path)
		got, err := os.ReadFile(path)
		want, ok := files[filepath.ToSlash(rel)]
		if err != nil || !ok || !bytes.Equal(want, got) {
			same = false
		}
		seen++
		return nil
	})
	return same && seen == len(files)
}

func writeFiles(dir string, files map[string]string) error {
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func copyFile(src, dst string, mode os.FileMode) error {
	b, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	if err := os.WriteFile(dst, b, mode); err != nil {
		return err
	}
	return os.Chmod(dst, mode)
}

func render(t *template.Template, data any) (string, error) {
	var b strings.Builder
	err := t.Execute(&b, data)
	return b.String(), err
}

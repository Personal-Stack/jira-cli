// Package sbx generates a Docker Sandboxes (sbx) environment in which an AI
// agent can use jira-cli while the Jira personal access token stays on the
// host:
//
//   - <project>/.sbx/jira-cli/: a local sbx kit (mixin) carrying the linux
//     jira binary, an egress rule for the Jira host, a proxy-managed
//     credential (the sandbox only sees a sentinel; the sbx proxy sets the
//     real Authorization header) and shell hooks;
//   - <project>/sbxenv.yaml: the environment `sbx env run` reads;
//   - <project>/.opencode/skills/jira: the agent skill;
//   - <settings>/config.yaml and bashrc: created once, mounted read-only at
//     the same path inside the sandbox.
//
// The formats follow the sandbox-kit-spec v3 (kits) and sbx environment
// files; see docs/sandbox.md.
package sbx

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"

	"gopkg.in/yaml.v3"

	"github.com/personal-stack/jira-cli/internal/credentials"
)

// GeneratedMarker starts every sbxenv.yaml this package writes. Files without
// it (or the marker of the former shell script) are never overwritten
// without Force.
const GeneratedMarker = "# generated by jira setup-sbx"

var legacyMarkers = []string{GeneratedMarker, "# generated by jira-cli scripts/sbx-setup.sh"}

// Options are the user's choices.
type Options struct {
	Project  string // workspace the agent works in (sbxenv.yaml goes here)
	Settings string // host folder with config.yaml and bashrc (outside Project)
	BaseURL  string // Jira base URL; empty: read from <Settings>/config.yaml

	Instance string // instance name in config.yaml
	CredRef  string // credential_ref in config.yaml
	Service  string // sbx secret / credential service name

	Agent    string // agent name (built-in, or the agent kit's name)
	AgentKit string // optional agent kit reference to compose
	Template string // optional sandbox image (sandboxOptions.template)
	Name     string // optional sandbox name

	CABundle string // optional CA file, copied into Settings
	ReadOnly bool   // read_only in config.yaml and JIRA_READ_ONLY=1
	Skill    bool   // copy the skill into <Project>/.opencode/skills/jira

	KitOnly bool // do not write sbxenv.yaml
	Force   bool // overwrite a foreign sbxenv.yaml and an edited skill
}

// Plan is validated Options plus everything derived from them.
type Plan struct {
	Options
	Host    string
	Port    int
	CredEnv string // JIRA_CREDENTIAL_<REF>

	KitDir, EnvFile, ConfigFile, BashrcFile, SkillDir string
}

var (
	plainPath = regexp.MustCompile(`^/[A-Za-z0-9._/-]*$`)
	plainName = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]*$`)
	kebab     = regexp.MustCompile(`^[a-z0-9][a-z0-9-]*$`)
	hostRe    = regexp.MustCompile(`^[A-Za-z0-9.-]+$`)
	imageRe   = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._/:@-]*$`)
	semverRe  = regexp.MustCompile(`^v?(\d+\.\d+\.\d+)`)
	baseURLRe = regexp.MustCompile(`^https://[A-Za-z0-9._~:/%+=,;-]+$`)
)

// AgentFromKit derives the agent name sbx uses for a kit reference: the last
// path segment without tag or digest (sbx/opencode:1.2@sha256:... -> opencode).
// sbx may report a different name; then the user passes it explicitly.
func AgentFromKit(ref string) string {
	h, _, _ := strings.Cut(ref, "@")
	if i := strings.LastIndex(h, "/"); i >= 0 {
		h = h[i+1:]
	}
	h, _, _ = strings.Cut(h, ":")
	return h
}

// NewPlan validates o. Paths must be absolute.
func NewPlan(o Options) (*Plan, error) {
	p := &Plan{Options: o}
	if !filepath.IsAbs(o.Project) {
		return nil, fmt.Errorf("project must be an absolute path: %q", o.Project)
	}
	if st, err := os.Stat(o.Project); err != nil || !st.IsDir() {
		return nil, fmt.Errorf("project directory not found: %s", o.Project)
	}
	p.Project = filepath.Clean(o.Project)
	p.Settings = filepath.Clean(o.Settings)
	// sbx mounts the settings at the same absolute path inside the sandbox,
	// and the path is written into shell snippets and YAML: keep it plain.
	if !plainPath.MatchString(p.Settings) {
		return nil, fmt.Errorf("settings path must be absolute and contain only letters, digits, '.', '_', '-' and '/': %q", o.Settings)
	}
	if p.Settings == p.Project || strings.HasPrefix(p.Settings+"/", p.Project+"/") {
		return nil, fmt.Errorf("the settings folder must be outside the project (%s is inside %s)", p.Settings, p.Project)
	}
	p.ConfigFile = filepath.Join(p.Settings, "config.yaml")
	p.BashrcFile = filepath.Join(p.Settings, "bashrc")
	p.KitDir = filepath.Join(p.Project, ".sbx", "jira-cli")
	p.EnvFile = filepath.Join(p.Project, "sbxenv.yaml")
	p.SkillDir = filepath.Join(p.Project, ".opencode", "skills", "jira")

	for _, c := range []struct{ name, v string }{{"instance", o.Instance}, {"credential ref", o.CredRef}, {"agent", o.Agent}} {
		if !plainName.MatchString(c.v) {
			return nil, fmt.Errorf("invalid %s %q (letters, digits, '.', '_', '-')", c.name, c.v)
		}
	}
	if o.Name != "" && !plainName.MatchString(o.Name) {
		return nil, fmt.Errorf("invalid sandbox name %q (letters, digits, '.', '_', '-')", o.Name)
	}
	if !kebab.MatchString(o.Service) {
		return nil, fmt.Errorf("invalid sbx secret name %q (lowercase letters, digits, '-')", o.Service)
	}
	for _, c := range []struct{ name, v string }{{"agent kit", o.AgentKit}, {"image", o.Template}} {
		if c.v != "" && !imageRe.MatchString(c.v) {
			return nil, fmt.Errorf("invalid %s reference %q", c.name, c.v)
		}
	}
	if o.CABundle != "" {
		if st, err := os.Stat(o.CABundle); err != nil || st.IsDir() {
			return nil, fmt.Errorf("CA bundle not found: %s", o.CABundle)
		}
	}

	if p.BaseURL == "" {
		p.BaseURL = BaseURLFromConfig(p.ConfigFile)
		if p.BaseURL == "" {
			return nil, errors.New("the Jira base URL is required (no config.yaml with base_url yet)")
		}
	}
	var err error
	if p.Host, p.Port, err = ParseBaseURL(p.BaseURL); err != nil {
		return nil, err
	}
	p.CredEnv = credentials.EnvName(o.CredRef)
	return p, nil
}

// BaseURLOrConfig is BaseURL, or the base_url of <Settings>/config.yaml.
func (o Options) BaseURLOrConfig() string {
	if o.BaseURL != "" {
		return o.BaseURL
	}
	return BaseURLFromConfig(filepath.Join(o.Settings, "config.yaml"))
}

// BaseURLFromConfig returns the first base_url in a jira-cli config file, or "".
func BaseURLFromConfig(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	var c struct {
		Default   string `yaml:"default_instance"`
		Instances map[string]struct {
			BaseURL string `yaml:"base_url"`
		} `yaml:"instances"`
	}
	if yaml.Unmarshal(b, &c) != nil {
		return ""
	}
	if in, ok := c.Instances[c.Default]; ok && in.BaseURL != "" {
		return in.BaseURL
	}
	for _, in := range c.Instances {
		if in.BaseURL != "" {
			return in.BaseURL
		}
	}
	return ""
}

// Previous holds the choices recorded in an sbxenv.yaml this package wrote.
type Previous struct {
	Agent, AgentKit, Template, Name string
	ReadOnly                        bool
}

// ReadPrevious reads the choices from a generated sbxenv.yaml. ok is false
// when the file is missing or was not generated by jira-cli.
func ReadPrevious(envFile string) (prev Previous, ok bool) {
	b, err := os.ReadFile(envFile)
	if err != nil || !IsGenerated(b) {
		return prev, false
	}
	var f struct {
		Name    string            `yaml:"name"`
		Agent   string            `yaml:"agent"`
		Kits    []any             `yaml:"kits"`
		Env     map[string]string `yaml:"env"`
		Options struct {
			Template string `yaml:"template"`
		} `yaml:"sandboxOptions"`
	}
	if yaml.Unmarshal(b, &f) != nil {
		return prev, false
	}
	prev = Previous{Agent: f.Agent, Name: f.Name, Template: f.Options.Template, ReadOnly: f.Env["JIRA_READ_ONLY"] == "1"}
	for _, k := range f.Kits {
		if s, isStr := k.(string); isStr && !strings.HasPrefix(s, ".") {
			prev.AgentKit = s
			break
		}
	}
	return prev, true
}

// IsGenerated reports whether an sbxenv.yaml was written by jira-cli.
func IsGenerated(b []byte) bool {
	for _, m := range legacyMarkers {
		if bytes.HasPrefix(b, []byte(m)) {
			return true
		}
	}
	return false
}

// CheckEnvFile refuses to overwrite a foreign sbxenv.yaml unless Force or KitOnly.
func (p *Plan) CheckEnvFile() error {
	if p.KitOnly || p.Force {
		return nil
	}
	b, err := os.ReadFile(p.EnvFile)
	if err != nil || IsGenerated(b) {
		return nil
	}
	return fmt.Errorf("%s exists and was not generated by jira-cli; use --kit-only and merge it by hand (docs/sandbox.md), or --force", p.EnvFile)
}

// KitVersion turns a CLI version into the kit's semver (dev builds: 0.0.0).
func KitVersion(v string) string {
	if m := semverRe.FindStringSubmatch(v); m != nil {
		return m[1]
	}
	return "0.0.0"
}

// WriteKit writes the kit. binaries maps a GOARCH ("amd64", "arm64") to a
// verified linux jira binary; the overlay installs the one matching the
// sandbox's architecture.
func (p *Plan) WriteKit(binaries map[string]string, version string) error {
	if len(binaries) == 0 {
		return errors.New("no linux binary for the kit")
	}
	if err := os.RemoveAll(p.KitDir); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(p.KitDir, "bin"), 0o755); err != nil {
		return err
	}
	for arch, src := range binaries {
		if err := copyFile(src, filepath.Join(p.KitDir, "bin", "jira-"+arch), 0o755); err != nil {
			return err
		}
	}
	files := map[string]string{
		".gitignore":          "bin/\n",
		"jira-cli.dockerfile": dockerfile,
	}
	var err error
	if files["profile.sh"], err = render(profileTmpl, p); err != nil {
		return err
	}
	kv := KitVersion(version)
	data := struct {
		*Plan
		KitVersion, ModeText string
	}{p, kv, "Read-only: every command that is not a read is refused before anything is sent (exit code 9). Do not try to work around it; ask the user."}
	if !p.ReadOnly {
		data.ModeText = "Writes are allowed. Preview every change with --dry-run first; destructive commands need --yes, which you must not add without the user's explicit approval."
	}
	if files["jira-cli.yaml"], err = render(kitTmpl, data); err != nil {
		return err
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(p.KitDir, name), []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// WriteSettings creates config.yaml and bashrc if missing (never
// overwrites) and copies the CA bundle. It returns notes for the user.
func (p *Plan) WriteSettings() (notes []string, err error) {
	if err := os.MkdirAll(p.Settings, 0o755); err != nil {
		return nil, err
	}
	caPath := ""
	if p.CABundle != "" {
		caPath = filepath.Join(p.Settings, strings.ReplaceAll(filepath.Base(p.CABundle), " ", "_"))
		if !plainPath.MatchString(caPath) {
			return nil, fmt.Errorf("rename the CA file to plain characters: %s", p.CABundle)
		}
		if err := copyFile(p.CABundle, caPath, 0o644); err != nil {
			return nil, err
		}
		notes = append(notes, "CA copied to "+caPath)
	}
	if b, err := os.ReadFile(p.ConfigFile); err == nil {
		notes = append(notes, "config kept: "+p.ConfigFile+" (edit it on the host)")
		s := string(b)
		if !regexp.MustCompile(`credential_ref:\s*` + regexp.QuoteMeta(p.CredRef) + `\s*(\n|$)`).MatchString(s) {
			notes = append(notes, "warning: "+p.ConfigFile+" does not use credential_ref: "+p.CredRef+"; the sandbox only provides "+p.CredEnv)
		}
		if caPath != "" && !strings.Contains(s, caPath) {
			notes = append(notes, "warning: add to "+p.ConfigFile+" under the instance:  tls: { ca_bundle: "+caPath+" }")
		}
		if strings.Contains(s, "/etc/jira-cli/") {
			notes = append(notes, "warning: "+p.ConfigFile+" refers to /etc/jira-cli/, which does not exist in the sandbox; use "+p.Settings+"/")
		}
	} else {
		cfg, err := render(configTmpl, struct {
			*Plan
			CAPath string
		}{p, caPath})
		if err != nil {
			return nil, err
		}
		if err := os.WriteFile(p.ConfigFile, []byte(cfg), 0o644); err != nil {
			return nil, err
		}
		notes = append(notes, "config created: "+p.ConfigFile)
	}
	if _, err := os.Stat(p.BashrcFile); err == nil {
		notes = append(notes, "bashrc kept: "+p.BashrcFile)
	} else {
		if err := os.WriteFile(p.BashrcFile, []byte(bashrc), 0o644); err != nil {
			return nil, err
		}
		notes = append(notes, "bashrc created: "+p.BashrcFile)
	}
	return notes, nil
}

// WriteSkill copies skill (the contents of the skill directory) to
// <Project>/.opencode/skills/jira. Local edits are kept unless Force.
func (p *Plan) WriteSkill(skill fs.FS) (note string, err error) {
	if _, err := os.Stat(p.SkillDir); err == nil && !p.Force {
		same, err := sameTree(skill, p.SkillDir)
		if err != nil {
			return "", err
		}
		if !same {
			return "warning: " + p.SkillDir + " differs from the bundled skill and was kept (local edits?); --force replaces it", nil
		}
	}
	if err := os.RemoveAll(p.SkillDir); err != nil {
		return "", err
	}
	err = fs.WalkDir(skill, ".", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		dst := filepath.Join(p.SkillDir, filepath.FromSlash(path))
		if d.IsDir() {
			return os.MkdirAll(dst, 0o755)
		}
		b, err := fs.ReadFile(skill, path)
		if err != nil {
			return err
		}
		mode := os.FileMode(0o644)
		if strings.HasSuffix(path, ".sh") {
			mode = 0o755
		}
		return os.WriteFile(dst, b, mode)
	})
	if err != nil {
		return "", err
	}
	return "skill: " + p.SkillDir, nil
}

// EnvFileContent renders sbxenv.yaml.
func (p *Plan) EnvFileContent() (string, error) { return render(envTmpl, p) }

// WriteEnvFile writes sbxenv.yaml (callers check CheckEnvFile first).
func (p *Plan) WriteEnvFile() error {
	s, err := p.EnvFileContent()
	if err != nil {
		return err
	}
	return os.WriteFile(p.EnvFile, []byte(s), 0o644)
}

func sameTree(a fs.FS, dir string) (bool, error) {
	seen := 0
	err := fs.WalkDir(a, ".", func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		seen++
		want, err := fs.ReadFile(a, path)
		if err != nil {
			return err
		}
		got, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(path)))
		if err != nil || !bytes.Equal(want, got) {
			return errDiffers
		}
		return nil
	})
	if errors.Is(err, errDiffers) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	n := 0
	_ = filepath.WalkDir(dir, func(_ string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			n++
		}
		return nil
	})
	return n == seen, nil
}

var errDiffers = errors.New("differs")

func copyFile(src, dst string, mode os.FileMode) error {
	b, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	if err := os.WriteFile(dst, b, mode); err != nil {
		return err
	}
	return os.Chmod(dst, mode)
}

func render(t *template.Template, data any) (string, error) {
	var b strings.Builder
	if err := t.Execute(&b, data); err != nil {
		return "", err
	}
	return b.String(), nil
}

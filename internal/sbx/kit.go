package sbx

// The global kit (jiracli sbx kit): one jira-cli kit for every sandbox of
// this machine, listed in the user's ~/.sbxenv.yaml, which sbx merges under
// every environment (lists concatenate, mappings merge by key):
//
//   - <settings>/kit/: the kit. What differs per Jira (host, port, sbx
//     secret, read-only) is a create-time kit arg, set where the kit is
//     listed, so one kit serves any environment and a project can override
//     an arg by listing the same source again;
//   - <settings>/config.yaml and bashrc: as for setup-sbx, created once;
//   - ~/.sbxenv.yaml: the kit with its args, <settings> mounted read-only
//     (the binary and the configuration are read from there), and the
//     binding that approves injecting the secret into requests to the host.
//
// Only these entries of ~/.sbxenv.yaml are added or replaced; the rest of
// the file, comments included, is kept.

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/personal-stack/jira-cli/internal/credentials"
)

const (
	// KitDirName is the global kit's folder in the settings folder.
	KitDirName = "kit"
	// UserEnvName is the user's environment defaults file in $HOME.
	UserEnvName = ".sbxenv.yaml"

	globalKitMarker = "Generated by jiracli sbx kit"
	// globalSkillPath is where the kit's image layer puts the skill.
	globalSkillPath = "/usr/share/jira-cli/skills/jira"
)

// KitOptions are the choices of `jiracli sbx kit`.
type KitOptions struct {
	Settings string // host folder with config.yaml, bashrc and kit/; mounted read-only
	BaseURL  string // Jira base URL; empty: from <Settings>/config.yaml
	Secret   string // sbx secret holding the PAT
	ReadOnly bool   // the readOnly kit arg (JIRA_READ_ONLY)
	Skill    bool   // bundle the jira skill
	Home     string // folder of the user's .sbxenv.yaml
}

// KitPlan is validated KitOptions plus what follows from them.
type KitPlan struct {
	KitOptions
	Host    string
	Port    int
	CredRef string // credential_ref in config.yaml
	CredEnv string // JIRA_CREDENTIAL_<REF>, the sentinel the sandbox sees

	KitDir, ConfigFile, BashrcFile, EnvFile string
}

// NewKitPlan validates o; paths must be absolute.
func NewKitPlan(o KitOptions) (*KitPlan, error) {
	k := &KitPlan{KitOptions: o, CredRef: "jira-prod"}
	k.Settings, k.Home = filepath.Clean(o.Settings), filepath.Clean(o.Home)
	if k.BaseURL == "" {
		k.BaseURL = BaseURLFromConfig(k.Settings)
	}
	if k.BaseURL == "" {
		return nil, errors.New("no Jira base URL: pass --base-url (or create " + filepath.Join(k.Settings, "config.yaml") + ")")
	}
	var err error
	if k.Host, k.Port, err = ParseBaseURL(k.BaseURL); err != nil {
		return nil, err
	}
	k.Host = strings.ToLower(k.Host)
	checks := []error{ValidSettingsPath(k.Settings), ValidSecretName(k.Secret)}
	if !filepath.IsAbs(k.Home) {
		checks = append(checks, fmt.Errorf("home %q is not absolute", k.Home))
	}
	if k.Settings == k.Home {
		checks = append(checks, errors.New("the settings folder must not be your home folder (it is mounted in every sandbox)"))
	}
	if err := errors.Join(checks...); err != nil {
		return nil, err
	}
	if ref := readConfig(filepath.Join(k.Settings, "config.yaml")).credRef; ref != "" && ValidName(ref) == nil {
		k.CredRef = ref // an existing config is kept: its credential_ref names the sentinel
	}
	k.CredEnv = credentials.EnvName(k.CredRef)
	k.KitDir = filepath.Join(k.Settings, KitDirName)
	k.ConfigFile = filepath.Join(k.Settings, "config.yaml")
	k.BashrcFile = filepath.Join(k.Settings, "bashrc")
	k.EnvFile = filepath.Join(k.Home, UserEnvName)
	return k, nil
}

// BinPath is the jiracli binary inside the sandbox: <settings> is mounted at
// the same path, so the kit's copy is there whether or not the kit's image
// layer was applied.
func (k *KitPlan) BinPath() string { return filepath.Join(k.KitDir, "bin", "jiracli") }

// SkillDir is the skill's folder in the kit (and, mounted, in the sandbox).
func (k *KitPlan) SkillDir() string { return filepath.Join(k.KitDir, "skill", skillName) }

// SkillPath is the skill as the agent instructions name it.
func (k *KitPlan) SkillPath() string { return k.SkillDir() }

// GlobalSkillPath is where the image layer puts the skill.
func (k *KitPlan) GlobalSkillPath() string { return globalSkillPath }

// Args are the kit args ~/.sbxenv.yaml sets, in order.
func (k *KitPlan) Args() [][2]string {
	return [][2]string{{"host", k.Host}, {"port", strconv.Itoa(k.Port)}, {"secret", k.Secret},
		{"readOnly", map[bool]string{true: "1", false: "0"}[k.ReadOnly]}}
}

// WriteKit writes the kit to dir (KitDir, or a scratch copy) with the linux
// jiracli binary and, when Skill, the skill.
func (k *KitPlan) WriteKit(dir, binary, version string, skill fs.FS) error {
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(dir, "bin"), 0o755); err != nil {
		return err
	}
	if err := copyFile(binary, filepath.Join(dir, "bin", "jiracli"), 0o755); err != nil {
		return err
	}
	if k.Skill {
		files, err := k.skillFiles(skill)
		if err != nil {
			return err
		}
		for path, b := range files {
			dst := filepath.Join(dir, "skill", skillName, filepath.FromSlash(path))
			if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
				return err
			}
			mode := os.FileMode(0o644)
			if strings.HasSuffix(path, ".sh") {
				mode = 0o755
			}
			if err := os.WriteFile(dst, b, mode); err != nil {
				return err
			}
		}
	}
	data := struct {
		*KitPlan
		KitVersion string
	}{k, KitVersion(version)}
	kit, err := render(globalKitTmpl, data)
	if err != nil {
		return err
	}
	df, err := render(globalDockerfileTmpl, data)
	if err != nil {
		return err
	}
	return writeFiles(dir, map[string]string{"jira-cli.yaml": kit, "jira-cli.dockerfile": df})
}

// skillFiles is the skill with the "This sandbox" section for the global kit.
func (k *KitPlan) skillFiles(skill fs.FS) (map[string][]byte, error) {
	files := map[string][]byte{}
	err := fs.WalkDir(skill, ".", func(path string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			files[path], err = fs.ReadFile(skill, path)
		}
		return err
	})
	if err != nil {
		return nil, err
	}
	md, ok := files["SKILL.md"]
	if !ok {
		return nil, errors.New("skill: SKILL.md missing")
	}
	section, err := render(globalSkillSectionTmpl, k)
	if err != nil {
		return nil, err
	}
	files["SKILL.md"] = insertAfterTitle(md, section)
	return files, nil
}

// WriteSettings creates config.yaml and bashrc when missing. A config this
// creates leaves read-only to the readOnly kit arg; an existing one is kept,
// and its read_only: true still wins over the arg.
func (k *KitPlan) WriteSettings() ([]Note, error) {
	data := *k
	data.ReadOnly = false
	notes, err := writeSettings(k.Settings, k.ConfigFile, k.BashrcFile, &data)
	if err != nil {
		return nil, err
	}
	if c := readConfig(k.ConfigFile); c.baseURL != "" && NormalizeBaseURL(c.baseURL) != k.BaseURL {
		notes = append(notes, Note{Warn: true, Text: fmt.Sprintf("%s has base_url %s, not %s: jiracli in the sandbox uses the file", k.ConfigFile, c.baseURL, k.BaseURL)})
	}
	if !k.ReadOnly && configReadOnly(k.ConfigFile) {
		notes = append(notes, Note{Warn: true, Text: k.ConfigFile + " sets read_only: true, which keeps jiracli read-only whatever the readOnly kit arg says"})
	}
	return notes, nil
}

func configReadOnly(path string) bool {
	b, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	var c struct {
		Instances map[string]struct {
			ReadOnly bool `yaml:"read_only"`
		} `yaml:"instances"`
	}
	if yaml.Unmarshal(b, &c) != nil {
		return false
	}
	for _, in := range c.Instances {
		if in.ReadOnly {
			return true
		}
	}
	return false
}

// IsGlobalKit reports whether dir holds a kit `jiracli sbx kit` generated.
func IsGlobalKit(dir string) bool {
	b, err := os.ReadFile(filepath.Join(dir, "jira-cli.yaml"))
	return err == nil && bytes.Contains(b, []byte(globalKitMarker))
}

// StrayUserEnv returns the path of a ~/.sbxenv.yml (in home), which sbx
// does not read (it reads ~/.sbxenv.yaml only), or "" if there is none.
func StrayUserEnv(home string) string {
	p := filepath.Join(home, ".sbxenv.yml")
	if _, err := os.Stat(p); err != nil {
		return ""
	}
	return p
}

// StrayUserEnvNote is the warning for StrayUserEnv's file.
func StrayUserEnvNote(path string) string {
	return path + " exists, but sbx reads only ~/" + UserEnvName +
		": its settings are not applied. Move them into ~/" + UserEnvName + " and remove it."
}

// UserEnvKit returns the source of the jira-cli kit that the user's
// ~/.sbxenv.yaml (in home) lists, or "" if it lists none.
func UserEnvKit(home string) string {
	b, err := os.ReadFile(filepath.Join(home, UserEnvName))
	if err != nil {
		return ""
	}
	var doc yaml.Node
	if yaml.Unmarshal(b, &doc) != nil || len(doc.Content) == 0 {
		return ""
	}
	kits := mapGet(doc.Content[0], "kits")
	if kits == nil || kits.Kind != yaml.SequenceNode {
		return ""
	}
	for _, e := range kits.Content {
		if src := kitSource(e); src != "" && IsGlobalKit(resolveFrom(home, src)) {
			return src
		}
	}
	return ""
}

// UserEnvContent returns ~/.sbxenv.yaml (existing, possibly empty) with the
// kit at kitDir listed with its args, <settings> mounted read-only and the
// binding for the host. Other entries and comments are kept. A kit entry
// that is a kit generated by `jiracli sbx kit` anywhere is replaced.
func (k *KitPlan) UserEnvContent(existing []byte, kitDir string) ([]byte, error) {
	root, doc, err := parseUserEnv(existing)
	if err != nil {
		return nil, err
	}
	if mapGet(root, "schemaVersion") == nil {
		mapSet(root, "schemaVersion", quoted("1"))
		// schemaVersion first, as everywhere else.
		n := len(root.Content)
		root.Content = append(root.Content[n-2:], root.Content[:n-2]...)
	}

	// kits: our entry, in place of an earlier one.
	kits := mapEnsure(root, "kits", yaml.SequenceNode)
	args := &yaml.Node{Kind: yaml.MappingNode}
	for _, a := range k.Args() {
		mapSet(args, a[0], quoted(a[1]))
	}
	entry := &yaml.Node{Kind: yaml.MappingNode}
	mapSet(entry, "source", plain(kitDir))
	mapSet(entry, "args", args)
	entry.HeadComment = "jira-cli for " + k.Host + " (jiracli sbx kit; re-run it to change)"
	replaced := false
	var keep []*yaml.Node
	for _, e := range kits.Content {
		src := kitSource(e)
		ours := src != "" && (resolveFrom(k.Home, src) == kitDir || resolveFrom(k.Home, src) == k.KitDir || IsGlobalKit(resolveFrom(k.Home, src)))
		switch {
		case ours && !replaced:
			if e.HeadComment != "" {
				entry.HeadComment = e.HeadComment
			}
			keep, replaced = append(keep, entry), true
		case ours: // a second one would provide jira-cli twice
		default:
			keep = append(keep, e)
		}
	}
	if !replaced {
		keep = append(keep, entry)
	}
	kits.Content = keep
	if kits.Style == yaml.FlowStyle {
		kits.Style = 0
	}

	// additionalWorkspaces: <settings>, read-only.
	ws := mapEnsure(root, "additionalWorkspaces", yaml.SequenceNode)
	mount := &yaml.Node{Kind: yaml.MappingNode}
	mapSet(mount, "path", plain(k.Settings))
	mapSet(mount, "readOnly", &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!bool", Value: "true"})
	mount.HeadComment = "jira-cli: the kit's binary, config.yaml and bashrc (read-only, same path)"
	replaced = false
	for i, e := range ws.Content {
		if p := mapGet(e, "path"); p != nil && resolveFrom(k.Home, p.Value) == k.Settings {
			if e.HeadComment != "" {
				mount.HeadComment = e.HeadComment
			}
			ws.Content[i], replaced = mount, true
			break
		}
	}
	if !replaced {
		ws.Content = append(ws.Content, mount)
	}
	if ws.Style == yaml.FlowStyle {
		ws.Style = 0
	}

	// bindings: approve the secret for the host; other domains are kept.
	b := mapEnsure(root, "bindings", yaml.MappingNode)
	svc := mapEnsure(b, k.Secret, yaml.MappingNode)
	apiKey := mapEnsure(svc, "apiKey", yaml.MappingNode)
	domains := mapEnsure(apiKey, "domains", yaml.SequenceNode)
	found := false
	for _, d := range domains.Content {
		found = found || strings.EqualFold(d.Value, k.Host)
	}
	if !found {
		domains.Content = append(domains.Content, plain(k.Host))
	}
	domains.Style = yaml.FlowStyle
	return encode(doc)
}

// RemoveFromUserEnv returns ~/.sbxenv.yaml without the kit entry and the
// mount of <settings>; bindings are left (they are approvals, recorded by
// sbx in its credentials.yaml anyway). removed is false when the file
// lists neither.
func (k *KitPlan) RemoveFromUserEnv(existing []byte) (out []byte, removed bool, err error) {
	root, doc, err := parseUserEnv(existing)
	if err != nil {
		return nil, false, err
	}
	if kits := mapGet(root, "kits"); kits != nil && kits.Kind == yaml.SequenceNode {
		var keep []*yaml.Node
		for _, e := range kits.Content {
			src := kitSource(e)
			if src != "" && (resolveFrom(k.Home, src) == k.KitDir || IsGlobalKit(resolveFrom(k.Home, src))) {
				removed = true
				continue
			}
			keep = append(keep, e)
		}
		kits.Content = keep
		if len(keep) == 0 {
			mapDelete(root, "kits")
		}
	}
	if ws := mapGet(root, "additionalWorkspaces"); ws != nil && ws.Kind == yaml.SequenceNode {
		var keep []*yaml.Node
		for _, e := range ws.Content {
			if p := mapGet(e, "path"); p != nil && resolveFrom(k.Home, p.Value) == k.Settings {
				removed = true
				continue
			}
			keep = append(keep, e)
		}
		ws.Content = keep
		if len(keep) == 0 {
			mapDelete(root, "additionalWorkspaces")
		}
	}
	out, err = encode(doc)
	return out, removed, err
}

// ValidationEnv is an environment file for `sbx env plan` in a scratch
// folder: the user's file with the kit at kitDir, and an agent and a
// workspace if the user's file sets none (a project file would).
func (k *KitPlan) ValidationEnv(existing []byte, kitDir, agent string) ([]byte, error) {
	b, err := k.UserEnvContent(existing, kitDir)
	if err != nil {
		return nil, err
	}
	root, doc, err := parseUserEnv(b)
	if err != nil {
		return nil, err
	}
	if a := mapGet(root, "agent"); a == nil || a.Value == "" {
		mapSet(root, "agent", plain(agent))
	}
	mapDelete(root, "workspace")
	mapSet(root, "workspace", plain("."))
	return encode(doc)
}

func parseUserEnv(existing []byte) (root, doc *yaml.Node, err error) {
	doc = &yaml.Node{}
	if len(bytes.TrimSpace(existing)) > 0 {
		if err := yaml.Unmarshal(existing, doc); err != nil {
			return nil, nil, fmt.Errorf("%s: %v", UserEnvName, err)
		}
	}
	if doc.Kind == 0 || len(doc.Content) == 0 {
		head := doc.HeadComment
		doc = &yaml.Node{Kind: yaml.DocumentNode, HeadComment: head, Content: []*yaml.Node{{Kind: yaml.MappingNode}}}
	}
	root = doc.Content[0]
	if root.Kind != yaml.MappingNode {
		return nil, nil, fmt.Errorf("%s is not a YAML mapping", UserEnvName)
	}
	return root, doc, nil
}

func encode(doc *yaml.Node) ([]byte, error) {
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// kitSource is a kits entry's source: the scalar, or the source field.
func kitSource(e *yaml.Node) string {
	switch e.Kind {
	case yaml.ScalarNode:
		return e.Value
	case yaml.MappingNode:
		if s := mapGet(e, "source"); s != nil {
			return s.Value
		}
	}
	return ""
}

// resolveFrom resolves a local path as sbx does in a file in dir; other
// references (registry, git) come back unchanged.
func resolveFrom(dir, p string) string {
	switch {
	case filepath.IsAbs(p):
		return filepath.Clean(p)
	case p == "." || p == ".." || strings.HasPrefix(p, "./") || strings.HasPrefix(p, "../"):
		return filepath.Join(dir, p)
	case strings.HasPrefix(p, "${{ env.fileDir }}"):
		return filepath.Join(dir, strings.TrimPrefix(p, "${{ env.fileDir }}"))
	}
	return p
}

func plain(v string) *yaml.Node { return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v} }

func quoted(v string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v, Style: yaml.DoubleQuotedStyle}
}

func mapGet(m *yaml.Node, key string) *yaml.Node {
	if m == nil || m.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			return m.Content[i+1]
		}
	}
	return nil
}

func mapSet(m *yaml.Node, key string, v *yaml.Node) {
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			v.HeadComment, v.LineComment = m.Content[i+1].HeadComment, m.Content[i+1].LineComment
			m.Content[i+1] = v
			return
		}
	}
	m.Content = append(m.Content, plain(key), v)
}

func mapDelete(m *yaml.Node, key string) {
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			m.Content = append(m.Content[:i], m.Content[i+2:]...)
			return
		}
	}
}

// mapEnsure returns m[key], created (or replaced, if null) with kind.
func mapEnsure(m *yaml.Node, key string, kind yaml.Kind) *yaml.Node {
	if v := mapGet(m, key); v != nil && v.Kind == kind {
		return v
	}
	v := &yaml.Node{Kind: kind}
	mapSet(m, key, v)
	return v
}

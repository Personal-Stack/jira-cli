package generator

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"github.com/personal-stack/jira-cli/internal/operation"
)

const header = "// Code generated by jiragen. DO NOT EDIT.\n// Source of truth: specs/manifest.yaml. Regenerate with `make generate`.\n\n"

// emitProfile renders one profile package: profile.go, one ops_<group>.go per
// command group and REPORT.md.
func emitProfile(pkg string, p *operation.Profile) (map[string][]byte, error) {
	files := map[string][]byte{}
	groups := map[string][]operation.Operation{}
	for _, op := range p.Operations {
		groups[op.Group] = append(groups[op.Group], op)
	}
	names := sortedKeys(groups)

	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "// Package %s holds the generated operations of profile %q.\npackage %s\n\n", pkg, p.Name, pkg)
	b.WriteString("import \"github.com/personal-stack/jira-cli/internal/operation\"\n\n")
	b.WriteString("// Profile is the compiled-in operation table.\nvar Profile = &operation.Profile{\n")
	fmt.Fprintf(&b, "Name: %s,\nDeployment: %s,\nBasePath: %s,\n", q(p.Name), q(p.Deployment), q(p.BasePath))
	fmt.Fprintf(&b, "Spec: %s,\n", source(p.Spec))
	if len(p.Overlays) > 0 {
		b.WriteString("Overlays: []operation.Source{\n")
		for _, o := range p.Overlays {
			b.WriteString(source(o) + ",\n")
		}
		b.WriteString("},\n")
	}
	if len(p.Skipped) > 0 {
		b.WriteString("Skipped: []operation.Skipped{\n")
		for _, s := range p.Skipped {
			fmt.Fprintf(&b, "{OperationID: %s, Method: %s, Path: %s, Reason: %s},\n", q(s.OperationID), q(s.Method), q(s.Path), q(s.Reason))
		}
		b.WriteString("},\n")
	}
	if len(p.Warnings) > 0 {
		b.WriteString("Warnings: []string{\n")
		for _, w := range p.Warnings {
			b.WriteString(q(w) + ",\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\nfunc init() {\n")
	for _, g := range names {
		fmt.Fprintf(&b, "Profile.Operations = append(Profile.Operations, %s...)\n", varName(g))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("profile.go: %w", err)
	}
	files["profile.go"] = src

	for _, g := range names {
		var b bytes.Buffer
		b.WriteString(header)
		fmt.Fprintf(&b, "package %s\n\nimport \"github.com/personal-stack/jira-cli/internal/operation\"\n\n", pkg)
		fmt.Fprintf(&b, "var %s = []operation.Operation{\n", varName(g))
		for _, op := range groups[g] {
			writeOp(&b, op)
		}
		b.WriteString("}\n")
		src, err := format.Source(b.Bytes())
		if err != nil {
			return nil, fmt.Errorf("group %s: %w", g, err)
		}
		files["ops_"+strings.ReplaceAll(g, "-", "_")+".go"] = src
	}
	files["REPORT.md"] = report(p)
	return files, nil
}

func emitRegistry(profiles []*operation.Profile) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("// Package generated registers every compiled-in profile.\npackage generated\n\nimport (\n")
	b.WriteString("\t\"github.com/personal-stack/jira-cli/internal/operation\"\n")
	sorted := append([]*operation.Profile{}, profiles...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	for _, p := range sorted {
		fmt.Fprintf(&b, "\t%q\n", "github.com/personal-stack/jira-cli/generated/"+PackageName(p.Name))
	}
	b.WriteString(")\n\n// Profiles lists compiled-in profiles by name.\nvar Profiles = map[string]*operation.Profile{\n")
	for _, p := range sorted {
		fmt.Fprintf(&b, "%s: %s.Profile,\n", q(p.Name), PackageName(p.Name))
	}
	fmt.Fprintf(&b, "}\n\n// DefaultProfile is used when an instance does not name one (first profile in the manifest).\nconst DefaultProfile = %s\n", q(profiles[0].Name))
	return format.Source(b.Bytes())
}

func varName(group string) string {
	var b strings.Builder
	b.WriteString("ops")
	for _, w := range splitWords(group) {
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

func q(s string) string { return strconv.Quote(s) }

func source(s operation.Source) string {
	return fmt.Sprintf("operation.Source{Name: %s, Kind: %s, Version: %s, Path: %s, SHA256: %s}", q(s.Name), q(s.Kind), q(s.Version), q(s.Path), q(s.SHA256))
}

func strs(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = q(s)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

// writeOp emits only non-zero fields so diffs stay focused.
func writeOp(b *bytes.Buffer, op operation.Operation) {
	b.WriteString("{\n")
	fmt.Fprintf(b, "Group: %s,\nName: %s,\nOperationID: %s,\nOriginalOperationID: %s,\nTag: %s,\nMethod: %s,\nPath: %s,\n",
		q(op.Group), q(op.Name), q(op.OperationID), q(op.OriginalOperationID), q(op.Tag), q(op.Method), q(op.Path))
	if op.Summary != "" {
		fmt.Fprintf(b, "Summary: %s,\n", q(op.Summary))
	}
	if op.Description != "" {
		fmt.Fprintf(b, "Description: %s,\n", q(op.Description))
	}
	if op.Deprecated {
		b.WriteString("Deprecated: true,\n")
	}
	if len(op.Params) > 0 {
		b.WriteString("Params: []operation.Param{\n")
		for _, p := range op.Params {
			fmt.Fprintf(b, "{Name: %s, In: %s, Type: %s", q(p.Name), q(string(p.In)), q(p.Type))
			if p.Flag != "" {
				fmt.Fprintf(b, ", Flag: %s", q(p.Flag))
			}
			if p.Array {
				b.WriteString(", Array: true")
			}
			if p.Required {
				b.WriteString(", Required: true")
			}
			if len(p.Enum) > 0 {
				fmt.Fprintf(b, ", Enum: %s", strs(p.Enum))
			}
			if p.Default != "" {
				fmt.Fprintf(b, ", Default: %s", q(p.Default))
			}
			if p.Description != "" {
				fmt.Fprintf(b, ", Description: %s", q(p.Description))
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	if bd := op.Body; bd != nil {
		fmt.Fprintf(b, "Body: &operation.Body{Mode: %s, ContentType: %s", q(string(bd.Mode)), q(bd.ContentType))
		if bd.Required {
			b.WriteString(", Required: true")
		}
		if bd.Schema != "" {
			fmt.Fprintf(b, ", Schema: %s", q(bd.Schema))
		}
		if bd.JSONType != "" {
			fmt.Fprintf(b, ", JSONType: %s", q(bd.JSONType))
		}
		if bd.MultipartField != "" {
			fmt.Fprintf(b, ", MultipartField: %s", q(bd.MultipartField))
		}
		if len(bd.Properties) > 0 {
			b.WriteString(", Properties: []operation.Property{\n")
			for _, p := range bd.Properties {
				fmt.Fprintf(b, "{Name: %s, Type: %s", q(p.Name), q(p.Type))
				if p.Required {
					b.WriteString(", Required: true")
				}
				if len(p.Enum) > 0 {
					fmt.Fprintf(b, ", Enum: %s", strs(p.Enum))
				}
				b.WriteString("},\n")
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	fmt.Fprintf(b, "Risk: %s,\nRiskSource: %s,\n", q(string(op.Risk)), q(op.RiskSource))
	if op.ConfirmationRequired {
		b.WriteString("ConfirmationRequired: true,\n")
	}
	if op.Idempotent {
		b.WriteString("Idempotent: true,\n")
	}
	if op.Pagination != nil {
		fmt.Fprintf(b, "Pagination: &operation.Pagination{StartParam: %s, LimitParam: %s},\n", q(op.Pagination.StartParam), q(op.Pagination.LimitParam))
	}
	if len(op.ResponseTypes) > 0 {
		fmt.Fprintf(b, "ResponseTypes: %s,\n", strs(op.ResponseTypes))
	}
	b.WriteString("},\n")
}

// report renders a human-reviewable summary of the generated command surface.
// Diffs of this file are the primary review artifact for spec updates.
func report(p *operation.Profile) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "<!-- Code generated by jiragen. DO NOT EDIT. -->\n# Generation report: %s\n\n", p.Name)
	fmt.Fprintf(&b, "- Spec: `%s` (%s) version `%s`, sha256 `%s`\n", p.Spec.Path, p.Spec.Kind, p.Spec.Version, p.Spec.SHA256)
	for _, o := range p.Overlays {
		fmt.Fprintf(&b, "- %s: `%s`, sha256 `%s`\n", o.Kind, o.Path, o.SHA256)
	}
	risk := map[string]int{}
	method := map[string]int{}
	for _, op := range p.Operations {
		risk[string(op.Risk)]++
		method[op.Method]++
	}
	fmt.Fprintf(&b, "\n## Summary\n\n| Metric | Count |\n|---|---|\n| Generated commands | %d |\n| Skipped operations | %d |\n| Warnings | %d |\n", len(p.Operations), len(p.Skipped), len(p.Warnings))
	for _, k := range sortedKeys(method) {
		fmt.Fprintf(&b, "| Method %s | %d |\n", k, method[k])
	}
	for _, k := range sortedKeys(risk) {
		fmt.Fprintf(&b, "| Risk %s | %d |\n", k, risk[k])
	}
	if len(p.Skipped) > 0 {
		b.WriteString("\n## Skipped operations\n\n| Method | Path | operationId | Reason |\n|---|---|---|---|\n")
		for _, s := range p.Skipped {
			fmt.Fprintf(&b, "| %s | `%s` | %s | %s |\n", s.Method, s.Path, s.OperationID, md(s.Reason))
		}
	}
	if len(p.Warnings) > 0 {
		b.WriteString("\n## Warnings\n\n")
		for _, w := range p.Warnings {
			fmt.Fprintf(&b, "- %s\n", md(w))
		}
	}
	b.WriteString("\n## Commands\n\n| Command | Method | Path | operationId | Risk | Body | Paginated |\n|---|---|---|---|---|---|---|\n")
	for _, op := range p.Operations {
		body := ""
		if op.Body != nil {
			body = string(op.Body.Mode)
		}
		pg := ""
		if op.Pagination != nil {
			pg = "yes"
		}
		fmt.Fprintf(&b, "| `%s %s` | %s | `%s` | %s | %s | %s | %s |\n", op.Group, op.Name, op.Method, op.Path, op.OperationID, op.Risk, body, pg)
	}
	return b.Bytes()
}

func md(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

#!/usr/bin/env bash
# Writes the license texts of everything compiled into the jiracli binary:
# the Go standard library/runtime and every module dependency of ./cmd/jiracli
# for linux, darwin and windows
# (the generator's dependencies are not shipped and are excluded).
# Usage: scripts/third-party-licenses.sh [output-file]   (default: stdout)
# Deterministic: modules sorted by path; reads only the local module cache.
set -euo pipefail
cd "$(dirname "$0")/.."
out=${1:-/dev/stdout}

license_file() { # first license-like file in a directory
  find "$1" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' \) | sort | head -n1
}

{
  echo "Third-party licenses for the jiracli binary"
  echo "========================================"
  echo
  echo "Generated by scripts/third-party-licenses.sh from the modules compiled into ./cmd/jiracli."
  echo
  goroot=$(go env GOROOT)
  echo "--------------------------------------------------------------------------------"
  echo "Go standard library and runtime ($(go env GOVERSION))"
  echo "--------------------------------------------------------------------------------"
  cat "$goroot/LICENSE"
  echo
  # Union over every release OS: dependencies differ per platform (e.g. the
  # keyring backends for macOS and Windows).
  for os in linux darwin windows; do
    GOOS=$os GOARCH=amd64 go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' ./cmd/jiracli
  done | sort -u |
  while read -r path version; do
    [ -n "$path" ] || continue
    dir=$(go list -m -f '{{.Dir}}' "$path")
    lf=$(license_file "$dir")
    echo "--------------------------------------------------------------------------------"
    echo "$path $version"
    echo "--------------------------------------------------------------------------------"
    if [ -n "$lf" ]; then cat "$lf"; else echo "(no license file found in the module; check upstream)"; fi
    # Apache-2.0 section 4(d): reproduce NOTICE files.
    for nf in $(find "$dir" -maxdepth 1 -type f -iname 'NOTICE*' | sort); do
      echo; echo "[NOTICE: $(basename "$nf")]"; cat "$nf"
    done
    echo
  done
} > "$out"
